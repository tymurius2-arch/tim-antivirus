DANGER_RU = {"critical": "критическая", "high": "высокая", "medium": "средняя", "low": "низкая", "info": "нет"}


@dataclass
class ThreatInfo:
    signature: str
    platform: str
    category: str
    family: str
    danger: str
    description: str
    family_note: str = ""
    advice: list[str] = field(default_factory=list)

    @property
    def danger_ru(self) -> str:
        return tr(DANGER_RU.get(self.danger, self.danger))

    def __post_init__(self):
        self.platform, self.category = tr(self.platform), tr(self.category)
        self.description, self.family_note = tr(self.description), tr(self.family_note)
        self.advice = [tr(a) for a in self.advice]


def describe(sig: str) -> ThreatInfo:
    raw = sig.replace(".UNOFFICIAL", "").strip()
    if raw.lower().startswith("ai.heuristic"):
        lvl = raw.split(".")[-1].lower()
        return ThreatInfo(sig, "—", "Эвристика Tim Antivirus", "—", "high" if lvl == "malicious" else "medium",
                          "Сигнатуры ClamAV не нашли известного вируса, но AI-анализ обнаружил признаки, типичные для "
                          "вредоносных программ (структура файла, подозрительные функции, расположение).",
                          advice=["Откройте файл в разделе «AI-анализ» и посмотрите признаки",
                                  "Проверьте файл в VirusTotal",
                                  "Если вы не знаете, откуда этот файл, поместите его в карантин"])
    base = re.sub(r"-\d+-\d+$", "", raw)
    parts = [p for p in base.split(".") if p]
    low = [p.lower() for p in parts]
    platform = next((PLATFORMS[p] for p in low if p in PLATFORMS), "—")
    cat_key = next((p for p in low if p in CATEGORIES), None)
    if cat_key is None:
        cat_key = next((k for k in CATEGORIES if any(k in p for p in low)), "malware")
    if "eicar" in raw.lower():
        cat_key = "test"
    title, danger, desc = CATEGORIES[cat_key]
    family = parts[-1] if parts else raw
    fam_note = next((v for k, v in FAMILIES.items() if k in raw.lower().replace("-", "").replace("_", "")), "")
    if low and low[0] == "pua":
        title, danger, desc = CATEGORIES["pua"]
    advice = {
        "critical": ["Немедленно поместите файл в карантин или удалите его",
                     "Смените пароли от важных аккаунтов с другого, чистого устройства",
                     "Выполните полное сканирование компьютера"],
        "high": ["Поместите файл в карантин", "Выполните полное сканирование компьютера",
                 "Не открывайте подобные файлы из непроверенных источников"],
        "medium": ["Поместите файл в карантин, если не уверены в его происхождении", "Проверьте файл в VirusTotal"],
        "low": ["Удалите программу, если она вам не нужна"],
        "info": ["Действий не требуется"],
    }[danger]
    return ThreatInfo(sig, platform, title, family, danger, desc, fam_note, advice)
